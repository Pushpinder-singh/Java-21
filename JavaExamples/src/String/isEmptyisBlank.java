package String;

public class isEmptyisBlank {
    public static void main(String[] args) {
        System.out.println("".isEmpty());
        System.out.println(" ".isEmpty());
        System.out.println("\n".isEmpty());

System.out.println();
        System.out.println("".isBlank());
        System.out.println(" ".isBlank());
        System.out.println("\n".isBlank());
    }
}
